import streamlit as st
import pandas as pd
import joblib

st.set_page_config(page_title="Heart Disease Prediction", layout="centered")

@st.cache_resource
def load_model():
    return joblib.load("model/model.joblib")

def main():
    st.title("Heart Disease Prediction")
    st.markdown("### Machine Learning Demonstration")
    st.write("Enter patient feature information below to receive a machine learning prediction.")
    
    try:
        pipeline = load_model()
    except Exception as e:
        st.error("Failed to load the model artifact. Ensure Phase 1 training has been completed.")
        return

    st.header("Patient / Feature Information")

    col1, col2 = st.columns(2)

    with col1:
        age = st.number_input("Age", min_value=20, max_value=100, value=50)
        sex_label = st.radio("Sex", options=["Male", "Female"])
        sex = 1 if sex_label == "Male" else 0
        
        cp = st.selectbox("Chest Pain Type (cp)", options=[1, 2, 3, 4])
        trestbps = st.number_input("Resting Blood Pressure (trestbps)", min_value=80, max_value=220, value=120)
        chol = st.number_input("Serum Cholestoral (chol)", min_value=100, max_value=600, value=200)
        
        fbs_label = st.radio("Fasting Blood Sugar > 120 mg/dl (fbs)", options=["Yes", "No"])
        fbs = 1 if fbs_label == "Yes" else 0
        
        restecg = st.selectbox("Resting ECG Results (restecg)", options=[0, 1, 2])

    with col2:
        thalach = st.number_input("Maximum Heart Rate (thalach)", min_value=60, max_value=220, value=150)
        
        exang_label = st.radio("Exercise Induced Angina (exang)", options=["Yes", "No"])
        exang = 1 if exang_label == "Yes" else 0
        
        oldpeak = st.number_input("ST Depression (oldpeak)", min_value=0.0, max_value=10.0, value=0.0, step=0.1)
        slope = st.selectbox("Slope of Peak Exercise ST Segment (slope)", options=[1, 2, 3])
        ca = st.selectbox("Number of Major Vessels (ca)", options=[0.0, 1.0, 2.0, 3.0])
        thal = st.selectbox("Thalassemia (thal)", options=[3.0, 6.0, 7.0])

    if st.button("Predict"):
        input_data = pd.DataFrame([{
            'age': age,
            'sex': sex,
            'cp': cp,
            'trestbps': trestbps,
            'chol': chol,
            'fbs': fbs,
            'restecg': restecg,
            'thalach': thalach,
            'exang': exang,
            'oldpeak': oldpeak,
            'slope': slope,
            'ca': ca,
            'thal': thal
        }])
        
        try:
            prediction = pipeline.predict(input_data)[0]
            probability = pipeline.predict_proba(input_data)[0][1] * 100
            
            st.subheader("Model Prediction")
            if prediction == 1:
                st.write("**Higher Risk**")
            else:
                st.write("**Lower Risk**")
                
            st.write(f"**Estimated Model Probability:** {probability:.1f}%")
        except Exception as e:
            st.error("An error occurred during prediction. Please verify input data.")

    st.divider()

    st.header("Model Information")
    st.write("Evaluation metrics on the hold-out test set from Phase 1:")
    metrics_col1, metrics_col2, metrics_col3, metrics_col4 = st.columns(4)
    metrics_col1.metric("Accuracy", "0.8852")
    metrics_col2.metric("Precision", "0.8387")
    metrics_col3.metric("Recall", "0.9286")
    metrics_col4.metric("F1 Score", "0.8814")

    st.write("*Recall measures the proportion of actual positive cases correctly identified by the model. A high recall minimizes false negatives.*")

    st.divider()

    st.warning("This application is an educational/research machine learning demonstration. The prediction is generated by a machine learning model and is NOT a medical diagnosis. Do not use this result for medical decisions. Consult a qualified healthcare professional for medical advice.")

if __name__ == "__main__":
    main()
